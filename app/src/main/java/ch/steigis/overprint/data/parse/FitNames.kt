/**
 * Display names for FIT manufacturer and Garmin product ids, generated from the
 * Garmin FIT SDK profile (version 21.217). Names come from the SDK's enum symbols,
 * or its comments where those name the product.
 */
internal object FitNames {
    fun manufacturer(id: Int): String? = manufacturers[id]

    /** Only meaningful when the manufacturer is Garmin (or its ANT arm Dynastream). */
    fun garminProduct(id: Int): String? = garminProducts[id]

    private val manufacturers: Map<Int, String> by lazy { parse(MANUFACTURERS) }
    private val garminProducts: Map<Int, String> by lazy { parse(GARMIN_PRODUCTS) }

    private fun parse(table: String): Map<Int, String> = table.lineSequence()
        .mapNotNull { line ->
            val eq = line.indexOf('=')
            if (eq <= 0) null else line.substring(0, eq).toIntOrNull()?.let { it to line.substring(eq + 1) }
        }
        .toMap()

